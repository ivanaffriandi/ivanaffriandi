export const staticMoments: MomentItem[] = [...LOCAL_FILENAMES].reverse().map((filename, idx) => {
  const index = idx + 1;
  // Progressively older dates
  const dateObj = new Date(Date.now() - idx * 24 * 60 * 60 * 1000 * 2.5);
  
  return {
    id: `local-${idx}`,
    url: `/images/moments/${filename}`,
    title: "",
    story: "",
    date: dateObj.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" }),
    location: "",
    published: dateObj.toISOString(),
    showOnHomepage: idx < 9,
    homepageOrder: idx
  };
});
