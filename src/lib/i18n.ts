export type LangCode = keyof typeof translations;
export type TransKeys = keyof typeof translations["en"];

export function getTranslation(key: TransKeys, lang: LangCode = "en", variables?: Record<string, any>): any {
  const dict = translations[lang] || translations["en"];
  let val: any = dict[key] !== undefined ? dict[key] : translations["en"][key];
  
  if (typeof val === "string" && variables) {
    Object.entries(variables).forEach(([k, v]) => {
      val = (val as string).replace(new RegExp(`{${k}}`, "g"), String(v));
    });
  }
  return val;
}
